// Do the POS routes still have the shape SCANnCART speaks?
//
// SCANnCART's desktop half calls two routes in this repo (`/api/pos/session` and `/api/pos/sync`),
// authenticates with one header, and reads the status codes those routes answer in. That is a
// contract with a codebase in another checkout, and nothing on that side can notice this repo moving
// it: both of the desktop's halves were written from these files, so a header renamed here *and* in
// its stand-in there would pass every test SCANnCART owns.
//
// So the surface is recorded in `scripts/pos-contract.json`, derived from this repo's own source by
// this script. A pull request that moves a route, renames the header, adds a status to `response.ts`
// or remaps a reconcile failure code fails here until the record is regenerated - which is what puts
// the change in the diff where a reviewer sees it. The point is not to forbid the change; it is to
// stop it travelling silently.
//
// The record is derived independently on each side rather than shared, deliberately: this one fails
// the pull request that moved the surface, while SCANnCART's own copy
// (`desktop/src/main/posContract.json`, re-recorded by `make verify-pos-contract`) fails there until
// it is re-recorded too. Two readings that must agree, rather than one file both sides trust.
//
// Run it:        node scripts/pos-contract.mjs
// Re-record it:  node scripts/pos-contract.mjs --write
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url)) // scripts/
const repoRoot = join(here, '..')
const CONTRACT = join(here, 'pos-contract.json')
const APP_POS = join('app', 'api', 'pos')
// Spelled POSIX in the messages, which are read in a log rather than joined into a path.
const APP_POS_SHOWN = 'app/api/pos'
const RESPONSE_HELPERS = join('app', 'api', 'helpers', 'response.ts')
const RECONCILE = join('app', 'api', 'model', 'pos_sync.ts')

const NOTE =
  'Generated by scripts/pos-contract.mjs from this repo\'s own POS route source. Do not edit by ' +
  'hand: run `node scripts/pos-contract.mjs --write`.'

const WRITE = process.argv.includes('--write')

// A checkout without the routes is an error rather than an empty contract: this script reads the
// files it is a contract for, so "found nothing" would otherwise read as "nothing changed".
if (!existsSync(join(repoRoot, APP_POS))) {
  console.error(`pos-contract: no POS routes at ${APP_POS_SHOWN} - nothing to check.`)
  console.error('pos-contract: this script derives the contract from the routes themselves, so it')
  console.error('pos-contract: cannot pass on a branch that does not carry them.')
  process.exit(1)
}

const read = (...parts) => readFileSync(join(repoRoot, ...parts), 'utf8')

/** Every SCANnCART-facing route, by the path Next.js derives from the directory it lives in. */
function routes() {
  const dir = join(repoRoot, APP_POS)
  const out = {}
  for (const segment of readdirSync(dir).sort()) {
    const file = join(dir, segment, 'route.ts')
    if (!existsSync(file)) continue
    const handler = /export async function (\w+)/.exec(readFileSync(file, 'utf8'))
    if (!handler) throw new Error(`no exported handler in ${APP_POS_SHOWN}/${segment}/route.ts`)
    out[`/api/pos/${segment}`] = handler[1]
  }
  if (Object.keys(out).length === 0) throw new Error(`no route files under ${APP_POS_SHOWN}`)
  return out
}

/** The header the routes authenticate with, read from them because they are where it is decided. */
function authHeader() {
  const dir = join(repoRoot, APP_POS)
  const found = new Set()
  for (const segment of readdirSync(dir)) {
    const file = join(dir, segment, 'route.ts')
    if (!existsSync(file)) continue
    const header = /headers\.get\(\s*['"]([^'"]+)['"]\s*\)/.exec(readFileSync(file, 'utf8'))
    if (header) found.add(header[1])
  }
  if (found.size !== 1) {
    throw new Error(
      `the POS routes do not agree on one auth header: ${found.size === 0 ? 'none found' : [...found].join(', ')}`
    )
  }
  return [...found][0]
}

/** `response.ts`'s helper -> its status: the vocabulary every route answers in. */
function statuses() {
  const out = {}
  for (const body of read(RESPONSE_HELPERS).split('export function ').slice(1)) {
    const name = /^(\w+)/.exec(body)?.[1]
    const status = /status:\s*(\d+)/.exec(body)?.[1]
    if (name && status) out[name] = Number(status)
  }
  if (Object.keys(out).length === 0) {
    throw new Error(`no response helper statuses found in ${RESPONSE_HELPERS}`)
  }
  return out
}

/** The reconcile's failure codes -> the helper each answers with, from `mapError`'s switch. */
function outcomes() {
  const body = /const mapError[\s\S]*?\n};/.exec(read(RECONCILE))?.[0]
  if (!body) throw new Error(`no mapError switch found in ${RECONCILE}`)

  const out = {}
  let pending = []
  for (const line of body.split('\n')) {
    const label = /^\s*case '([^']+)':\s*$/.exec(line)?.[1] ?? /^\s*(default):\s*$/.exec(line)?.[1]
    if (label) {
      pending.push(label)
      continue
    }
    const returned = /^\s*return (\w+)\(/.exec(line)?.[1]
    if (returned && pending.length > 0) {
      // One `return` can serve several stacked `case`s - the whole conflict family shares one.
      for (const key of pending) out[key] = returned
      pending = []
    }
  }
  if (Object.keys(out).length === 0) throw new Error(`no error cases found in ${RECONCILE}`)
  return out
}

function derive() {
  return {
    auth_header: authHeader(),
    note: NOTE,
    outcomes: outcomes(),
    routes: routes(),
    statuses: statuses()
  }
}

/** Keys in a fixed order at every level, so the file is stable and a diff is the surface moving. */
function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical)
  if (value !== null && typeof value === 'object') {
    const sorted = {}
    for (const key of Object.keys(value).sort()) sorted[key] = canonical(value[key])
    return sorted
  }
  return value
}

const render = (value) => `${JSON.stringify(canonical(value), null, 2)}\n`

let derived
try {
  derived = derive()
} catch (error) {
  console.error(`pos-contract: ${error.message}`)
  console.error('pos-contract: the extraction is what broke, so nothing was compared. This is')
  console.error('pos-contract: the one failure that is about this script rather than the contract.')
  process.exit(1)
}

if (WRITE) {
  writeFileSync(CONTRACT, render(derived))
  console.log(`pos-contract: wrote ${CONTRACT}`)
} else {
  if (!existsSync(CONTRACT)) {
    console.error(`pos-contract: no recorded contract at ${CONTRACT}`)
    console.error('pos-contract: create it with --write.')
    process.exit(1)
  }

  const recorded = JSON.parse(readFileSync(CONTRACT, 'utf8'))
  const drifted = Object.keys(derived).filter((key) => render(derived[key]) !== render(recorded[key]))

  if (drifted.length > 0) {
    console.error('pos-contract: the recorded POS surface no longer matches this repo\'s routes')
    for (const key of drifted) {
      console.error(`  ${key}:`)
      console.error(`    routes now:   ${JSON.stringify(canonical(derived[key]))}`)
      console.error(`    recorded:     ${JSON.stringify(canonical(recorded[key]))}`)
    }
    console.error('pos-contract: if the change is deliberate, re-record it with')
    console.error('pos-contract:   node scripts/pos-contract.mjs --write')
    console.error('pos-contract: and say so in the pull request - SCANnCART has to follow.')
    process.exit(1)
  }

  console.log('pos-contract: the recorded POS surface matches this repo\'s routes')
  console.log(
    `pos-contract: ${Object.keys(derived.routes).length} route(s), ` +
      `${Object.keys(derived.statuses).length} status(es), auth header "${derived.auth_header}"`
  )
}
